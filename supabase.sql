create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  subject text not null,
  title text not null,
  due date not null,
  done boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.tasks
  add column if not exists user_id uuid references auth.users(id) default auth.uid();

create table if not exists public.guestbook_entries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 30),
  message text not null check (char_length(message) between 1 and 300),
  created_at timestamptz not null default now()
);

alter table public.tasks enable row level security;
alter table public.guestbook_entries enable row level security;

drop policy if exists "Allow public read tasks" on public.tasks;
drop policy if exists "Allow public insert tasks" on public.tasks;
drop policy if exists "Allow public update tasks" on public.tasks;
drop policy if exists "Allow public delete tasks" on public.tasks;
drop policy if exists "Users can read own tasks" on public.tasks;
drop policy if exists "Users can add own tasks" on public.tasks;
drop policy if exists "Users can update own tasks" on public.tasks;
drop policy if exists "Users can delete own tasks" on public.tasks;
create policy "Users can read own tasks" on public.tasks for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users can add own tasks" on public.tasks for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Users can update own tasks" on public.tasks for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Users can delete own tasks" on public.tasks for delete to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Allow public read guestbook" on public.guestbook_entries;
drop policy if exists "Allow public insert guestbook" on public.guestbook_entries;
create policy "Allow public read guestbook" on public.guestbook_entries for select to anon, authenticated using (true);
create policy "Allow public insert guestbook" on public.guestbook_entries for insert to anon, authenticated with check (true);
